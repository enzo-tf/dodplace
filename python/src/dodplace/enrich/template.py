#: Header of the generated CSV. Every column is understood by
#: `dodplace enrich parts`, so the file can be re-imported untouched.
SKELETON_COLUMNS = (
    "LCSC Part #",
    "MPN",
    "Footprint",
    "Comment",
    "Designator",
    "Height (mm)",
    "Mass (g)",
    "Power (W)",
    "Datasheet",
)




@dataclass
class SkeletonRow:
    """One line item: a supplier code and the board parts it covers."""

    code: str
    refs: list[str]
    footprint: str = ""
    value: str = ""
    mpn: str = ""

    def designators(self) -> str:
        listed = " ".join(self.refs[:3])
        suffix = " …" if len(self.refs) > 3 else ""
        return f"{len(self.refs)}x {listed}{suffix}"


def supplier_code(component: dict) -> str:
    return field_value(component, SUPPLIER_FIELDS)


def skeleton_rows(doc: dict) -> list[SkeletonRow]:
    """Group the board's parts by supplier code, ready to be filled in.

    Only supplier-coded parts get a row: a parts file is matched by LCSC code,
    MPN or footprint, and a code is the only identity that can carry real
    dimensions. One row per code, not per component.
    """
    grouped: dict[str, list[dict]] = defaultdict(list)
    for component in doc.get("components", []):
        code = supplier_code(component)
        if code:
            grouped[code].append(component)

    rows = []
    for code in sorted(grouped):
        components = grouped[code]
        footprints = Counter(c.get("fpid", "") for c in components)
        values = Counter(str(c.get("value", "")) for c in components if c.get("value"))
        mpn = next((field_value(c, MPN_FIELDS) for c in components
                    if field_value(c, MPN_FIELDS)), "")
        rows.append(
            SkeletonRow(
                code=code,
                refs=sorted((str(c["ref"]) for c in components), key=_natural_key),
                footprint=footprints.most_common(1)[0][0] if footprints else "",
                value=values.most_common(1)[0][0] if values else "",
                mpn=mpn,
            )
        )
    return rows


def render_skeleton(rows: list[SkeletonRow], *, generated_by: str = "dodplace enrich skeleton"
                    ) -> str:
    """The CSV text: identity columns filled, the four data columns empty."""
    import csv
    import io

    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(SKELETON_COLUMNS)
    for row in rows:
        writer.writerow([
            row.code,
            row.mpn,
            row.footprint,
            row.value,
            row.designators(),
            "",  # Height (mm)
            "",  # Mass (g)
            "",  # Power (W)
            "",  # Datasheet
        ])
    header = (
        f"# {generated_by}: pre-filled from the board, to be completed by hand.\n"
        f"# Every column is understood by `dodplace enrich parts`, so this file can\n"
        f"# be re-imported as-is once filled in.\n"
    )
    return header + buffer.getvalue()


def summary(doc: dict) -> Counter:
    """Counts by prefix, for the console message."""
    hints = hints_from_extract(doc)
    return Counter({prefix: len(refs) for prefix, refs in hints.by_prefix.items()})
